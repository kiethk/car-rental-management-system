-- Schema for Car Rental Management System
-- SLOT = rental time window for a vehicle type.
--
-- WARNING: re-running this script DROPS every table and ALL data, then recreates an empty schema.
-- Run database/seed.sql right after it, then register new accounts (see README).

BEGIN;

-- Children first; CASCADE also removes any foreign key that still points at a dropped table.
-- "policies" is the old table replaced by contract_templates; dropped so older databases are cleaned up too.
DROP TABLE IF EXISTS booking_fees CASCADE;
DROP TABLE IF EXISTS issues CASCADE;
DROP TABLE IF EXISTS vehicle_inspections CASCADE;
DROP TABLE IF EXISTS reviews CASCADE;
DROP TABLE IF EXISTS payments CASCADE;
DROP TABLE IF EXISTS contracts CASCADE;
DROP TABLE IF EXISTS contract_templates CASCADE;
DROP TABLE IF EXISTS policies CASCADE;
DROP TABLE IF EXISTS bookings CASCADE;
DROP TABLE IF EXISTS slots CASCADE;
DROP TABLE IF EXISTS license_documents CASCADE;
DROP TABLE IF EXISTS promotions CASCADE;
DROP TABLE IF EXISTS license_plates CASCADE;
DROP TABLE IF EXISTS vehicles CASCADE;
DROP TABLE IF EXISTS vehicle_types CASCADE;
DROP TABLE IF EXISTS employees CASCADE;
DROP TABLE IF EXISTS customers CASCADE;

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE employees (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    CHECK (role IN ('admin','staff'))
);

CREATE TABLE vehicle_types (
    vehicle_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    brand VARCHAR(100) NOT NULL,
    category VARCHAR(30) NOT NULL,
    seats INTEGER NOT NULL,
    transmission VARCHAR(20) NOT NULL,
    fuel_type VARCHAR(20) NOT NULL,
    price_per_hour NUMERIC(14,2) NOT NULL,
    description VARCHAR(2000),
    image_url VARCHAR(500),
    CHECK (seats > 0),
    CHECK (price_per_hour >= 0)
);

-- registration_expiry belongs to the vehicle (the inspection sticker), not to a plate: changing the plate does not renew it.
CREATE TABLE vehicles (
    vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type_id BIGINT NOT NULL REFERENCES vehicle_types(vehicle_type_id),
    color VARCHAR(50) NOT NULL,
    year INTEGER NOT NULL,
    odometer INTEGER NOT NULL,
    registration_expiry DATE,
    status VARCHAR(30) NOT NULL,
    CHECK (odometer >= 0),
    CHECK (status IN ('available','rented','maintenance'))
);

-- One vehicle has many plates over its life (1-N). A plate belongs to exactly one vehicle and is never reused.
-- valid_from..valid_to is the period the plate was on the car; valid_to IS NULL means "current plate".
CREATE TABLE license_plates (
    license_plate_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(vehicle_id),
    plate VARCHAR(20) NOT NULL UNIQUE,
    province VARCHAR(100),
    valid_from TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valid_to TIMESTAMP WITH TIME ZONE,
    CHECK (valid_to IS NULL OR valid_to > valid_from),
    -- A vehicle never has two plates at the same time (this also allows only one open-ended row per vehicle).
    EXCLUDE USING gist (vehicle_id WITH =, tstzrange(valid_from, valid_to) WITH &&)
);

CREATE TABLE promotions (
    promotion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    discount_type VARCHAR(20) NOT NULL,
    discount_value NUMERIC(14,2) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    quantity INTEGER NOT NULL,
    CHECK (discount_type IN ('percent','fixed')),
    CHECK (discount_value >= 0),
    CHECK (discount_type <> 'percent' OR discount_value <= 100),
    CHECK (quantity >= 0),
    CHECK (start_date <= end_date)
);

CREATE TABLE license_documents (
    license_document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
    reviewed_by BIGINT REFERENCES employees(employee_id),
    license_number VARCHAR(50) NOT NULL,
    license_class VARCHAR(20) NOT NULL,
    license_expiry DATE NOT NULL,
    license_image_url VARCHAR(500) NOT NULL,
    status VARCHAR(30) NOT NULL,
    rejection_reason VARCHAR(500),
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    CHECK (status IN ('pending','approved','rejected'))
);

CREATE TABLE slots (
    slot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type_id BIGINT NOT NULL REFERENCES vehicle_types(vehicle_type_id),
    start_time TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time TIMESTAMP WITH TIME ZONE NOT NULL,
    capacity INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL,
    CHECK (start_time < end_time),
    CHECK (capacity > 0),
    CHECK (status IN ('open','closed'))
);

CREATE TABLE bookings (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
    slot_id BIGINT NOT NULL REFERENCES slots(slot_id),
    vehicle_id BIGINT REFERENCES vehicles(vehicle_id),
    employee_id BIGINT REFERENCES employees(employee_id),
    promotion_id BIGINT REFERENCES promotions(promotion_id),
    pickup_time TIMESTAMP WITH TIME ZONE NOT NULL,
    scheduled_end_time TIMESTAMP WITH TIME ZONE NOT NULL,
    actual_return_time TIMESTAMP WITH TIME ZONE,
    late_fee NUMERIC(14,2) NOT NULL DEFAULT 0.00,
    total_price NUMERIC(14,2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMP WITH TIME ZONE,
    price_per_hour NUMERIC(14,2) NOT NULL,
    deposit_amount NUMERIC(14,2) NOT NULL,
    discount_amount NUMERIC(14,2) NOT NULL,
    -- Plate text copied when the contract is issued and again at handover, so later plate changes never rewrite history.
    license_plate VARCHAR(20),
    CHECK (pickup_time < scheduled_end_time),
    CHECK (status IN ('pending_payment','confirmed','active','completed','cancelled')),
    CHECK (total_price >= 0 AND price_per_hour >= 0 AND deposit_amount >= 0 AND discount_amount >= 0 AND late_fee >= 0)
);

-- One row = one immutable version of the rental terms. Only DRAFT rows may be edited.
CREATE TABLE contract_templates (
    contract_template_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no INTEGER NOT NULL UNIQUE,
    title VARCHAR(150) NOT NULL,
    terms_content TEXT NOT NULL,
    deposit_rate NUMERIC(5,4) NOT NULL,
    late_fee_multiplier NUMERIC(5,2) NOT NULL,
    free_cancellation_hours INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_by BIGINT REFERENCES employees(employee_id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    activated_at TIMESTAMP WITH TIME ZONE,
    CHECK (status IN ('DRAFT','ACTIVE','ARCHIVED')),
    CHECK (deposit_rate > 0 AND deposit_rate <= 1),
    CHECK (late_fee_multiplier >= 1),
    CHECK (free_cancellation_hours >= 0)
);

-- Contract validity follows bookings.status; this table only stores the acceptance evidence and the PDF.
CREATE TABLE contracts (
    contract_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_number VARCHAR(50) NOT NULL UNIQUE,
    booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(booking_id),
    contract_template_id BIGINT NOT NULL REFERENCES contract_templates(contract_template_id),
    accepted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    accepted_ip VARCHAR(45),
    file_name VARCHAR(255),
    issued_at TIMESTAMP WITH TIME ZONE,
    emailed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(booking_id),
    transaction_code VARCHAR(100),
    payment_type VARCHAR(40) NOT NULL,
    amount NUMERIC(14,2) NOT NULL,
    payment_method VARCHAR(30) NOT NULL DEFAULT 'VNPAY',
    status VARCHAR(30) NOT NULL,
    paid_at TIMESTAMP WITH TIME ZONE,
    CHECK (status IN ('pending','paid','failed')),
    CHECK (amount >= 0)
);

CREATE TABLE reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(booking_id),
    rating INTEGER NOT NULL,
    comment VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (rating BETWEEN 1 AND 5)
);

CREATE TABLE vehicle_inspections (
    vehicle_inspection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(vehicle_id),
    scheduled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    status VARCHAR(30) NOT NULL,
    notes VARCHAR(1000),
    CHECK (status IN ('scheduled','passed','failed'))
);

CREATE TABLE issues (
    issue_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT REFERENCES bookings(booking_id),
    slot_id BIGINT REFERENCES slots(slot_id),
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(vehicle_id),
    employee_id BIGINT REFERENCES employees(employee_id),
    issue_type VARCHAR(30) NOT NULL,
    subject VARCHAR(200) NOT NULL,
    status VARCHAR(30) NOT NULL,
    evidence_url VARCHAR(500),
    reported_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (status IN ('open','in_progress','resolved'))
);

CREATE TABLE booking_fees (
    booking_fee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(booking_id),
    fee_type VARCHAR(40) NOT NULL,
    amount NUMERIC(14,2) NOT NULL,
    description VARCHAR(255) NOT NULL,
    issue_id BIGINT REFERENCES issues(issue_id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX ux_customers_email_lower ON customers (LOWER(email));

CREATE UNIQUE INDEX ux_employees_email_lower ON employees (LOWER(email));

CREATE INDEX ix_slots_type_time ON slots (vehicle_type_id, start_time, end_time);

CREATE INDEX ix_bookings_slot_status ON bookings (slot_id, status);

CREATE INDEX ix_bookings_vehicle_time ON bookings (vehicle_id, pickup_time, scheduled_end_time);

CREATE INDEX ix_bookings_customer ON bookings (customer_id);

CREATE INDEX ix_license_documents_customer ON license_documents (customer_id);

CREATE INDEX ix_issues_booking ON issues (booking_id);

CREATE INDEX ix_inspections_vehicle ON vehicle_inspections (vehicle_id);

CREATE INDEX ix_contracts_booking ON contracts (booking_id);

CREATE UNIQUE INDEX ux_contract_templates_single_active ON contract_templates (status) WHERE status = 'ACTIVE';

CREATE UNIQUE INDEX ux_contract_templates_single_draft ON contract_templates (status) WHERE status = 'DRAFT';

CREATE INDEX ix_booking_fees_booking ON booking_fees (booking_id);

CREATE INDEX ix_booking_fees_issue ON booking_fees (issue_id);

COMMIT;
